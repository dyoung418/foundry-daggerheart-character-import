// Draft translation of the level-5 ranger sample's levelUps into the system's levelData.levelups
// shape, per docs/mapping.md. Compendium uuids come from the system's src/packs; embedded item
// uuids are placeholders the writer fills in at import time.
import { readFileSync, writeFileSync } from "node:fs";
import { globSync } from "node:fs";
const S = process.argv[2], OUT = process.argv[3];
const byName = {};
for (const f of globSync(`${S}/dh-system/src/packs/**/*.json`)) {
  const d = JSON.parse(readFileSync(f, "utf8"));
  if (d.type && d.name) byName[`${d.type}|${d.name.normalize("NFKD").replace(/’/g, "'").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim()}`] = { id: d._id, pack: f.split("/src/packs/")[1].split("/")[0] };
}
const B = "/home/danny/daggerheart-character-builder/data/srd_2_0/";
const names = {};
for (const [file, kind] of [["domain-cards", "domainCard"], ["classes", "class"], ["subclasses", "subclass"]]) {
  for (const r of JSON.parse(readFileSync(`${B}${file}.json`, "utf8"))) names[r.id] = { kind, name: typeof r.name === "string" ? r.name[0] + r.name.slice(1).toLowerCase() : r.name["en-US"] };
}
const packOf = { domainCard: "domains", class: "classes", subclass: "subclasses" };
const uuid = (id) => { const n = names[id]; const k = `${n.kind}|${n.name.normalize("NFKD").replace(/’/g, "'").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim()}`; const m = byName[k]; if (!m) throw new Error("no match " + id); return `Compendium.daggerheart.${m.pack}.Item.${m.id}`; };

const ch = JSON.parse(readFileSync("samples/level5-ranger-multiclass.json", "utf8")).characters[0];
const expIds = Object.fromEntries(ch.experiences.map((e, i) => [e.id, `EXP_${i + 1}_FOUNDRY_ID`]));
const tierOf = (l) => (l <= 4 ? 2 : l <= 7 ? 3 : 4);
const tierCap = { 2: 4, 3: 7, 4: 10 };
const boxes = {};
const levelups = {};
for (const e of ch.levelUps) {
  const L = e.level, T = tierOf(L);
  const ach = { experiences: {}, domainCards: e.mandatoryCardId ? [{ uuid: uuid(e.mandatoryCardId), itemUuid: "Actor.<id>.Item.<id>" }] : [], proficiency: [2, 5, 8].includes(L) ? 1 : 0 };
  for (const x of ch.experiences) if (x.sinceLevel === L) ach.experiences[expIds[x.id]] = { name: x.name, modifier: 2 };
  const selections = [];
  for (const p of e.picks) {
    const key = p.key === "traits" ? "trait" : p.key;
    const cost = ["proficiency", "multiclass"].includes(key) ? 2 : 1;
    boxes[`${T}|${key}`] = (boxes[`${T}|${key}`] || 0) + 1;
    const sel = { tier: T, level: L, optionKey: key, type: key, subType: null, checkboxNr: boxes[`${T}|${key}`], value: ["hitPoint", "stress", "evasion", "proficiency", "experience"].includes(key) ? 1 : null, minCost: cost, amount: key === "trait" || key === "experience" ? 2 : key === "domainCard" ? 1 : null, data: [], secondaryData: {}, itemUuid: null, features: [] };
    if (key === "trait") sel.data = p.traits;
    if (key === "experience") sel.data = p.experienceIds.map((i) => expIds[i]);
    if (key === "domainCard") { sel.data = [uuid(p.cardId)]; sel.secondaryData = { limit: String(Math.min(Math.floor(L / 2), tierCap[T])) }; sel.itemUuid = "Actor.<id>.Item.<id>"; }
    if (key === "subclass") sel.secondaryData = { isMulticlass: p.target === "multiclass" ? "true" : "false", featureState: "<2|3>" };
    if (key === "multiclass") { sel.data = [uuid(p.classId)]; sel.secondaryData = { subclass: uuid(p.subclassId), domain: p.domain.toLowerCase() }; sel.itemUuid = "Actor.<id>.Item.<multiclass class item id>"; }
    selections.push(sel);
  }
  levelups[L] = { achievements: ach, selections };
}
writeFileSync(OUT, JSON.stringify({ _comment: "DRAFT expected system.levelData.levelups for samples/level5-ranger-multiclass.json, generated by tools/expected-levelups.mjs per docs/mapping.md. Placeholder uuids are filled by the writer at import time. Verify checkboxNr and secondaryData.limit against a real level-up in the system before trusting.", experienceIdMap: expIds, levelups }, null, 2) + "\n");
console.log("ok", Object.keys(levelups));
